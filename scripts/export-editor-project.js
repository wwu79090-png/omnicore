#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export function exportEditorProject({
  out = path.join('dist', 'editor-runnable-project'),
  projectName = 'omnicore-editor-export',
  generatedAt = new Date().toISOString()
} = {}) {
  const target = path.resolve(out);
  const scenePath = 'scenes/main.scene.json';
  const files = [
    ['package.json', JSON.stringify({
      name: projectName,
      private: true,
      type: 'module',
      scripts: {
        dev: 'vite --host 0.0.0.0',
        build: 'vite build',
        preview: 'vite preview --host 0.0.0.0'
      },
      dependencies: {
        omnicore: '^1.0.0',
        vite: '^8.0.16'
      }
    }, null, 2)],
    ['index.html', renderHtml(projectName)],
    ['src/main.js', renderMain(scenePath)],
    ['assets/manifest.json', JSON.stringify({
      format: 'OmniCore.AssetManifest',
      version: 1,
      generatedAt,
      entry: 'src/main.js',
      entryScene: scenePath,
      scenes: [scenePath],
      assets: [],
      targets: ['web']
    }, null, 2)],
    [scenePath, JSON.stringify({
      name: 'main',
      entities: [
        { id: 'hero', type: 'sprite', x: 120, y: 120, width: 48, height: 48, color: '#38bdf8' }
      ]
    }, null, 2)],
    ['README.md', `# ${projectName}\n\nGenerated by OmniCore editor export.\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`]
  ];

  for (const [file, content] of files) {
    const full = path.join(target, file);
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, `${content.trimEnd()}\n`, 'utf8');
  }
  return { ok: true, out: target, files: files.map(([file]) => file) };
}

function renderHtml(projectName) {
  return `<!doctype html>
<html lang="zh-CN">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${projectName}</title>
  </head>
  <body>
    <div id="app"></div>
    <script type="module" src="/src/main.js"></script>
  </body>
</html>`;
}

function renderMain(scenePath) {
  return `import OmniCore from 'omnicore';
import sceneData from '../${scenePath}' assert { type: 'json' };

const game = await new OmniCore.Game({ parent: '#app', renderer: 'auto', roundPixels: true }).init();
const scene = new OmniCore.Scene(sceneData.name || 'main');

for (const entity of sceneData.entities || []) {
  scene.add(new OmniCore.Sprite(entity.texture || entity.id, entity));
}

game.scene.register(scene);
await game.scene.push(scene.name);`;
}

function parseArgs(argv = []) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg.startsWith('--')) continue;
    const key = arg.slice(2);
    const value = argv[index + 1];
    if (!value || value.startsWith('--')) options[key] = true;
    else {
      options[key] = value;
      index += 1;
    }
  }
  return options;
}

function isCli() {
  return process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
}

if (isCli()) {
  const result = exportEditorProject(parseArgs(process.argv.slice(2)));
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

export default exportEditorProject;
