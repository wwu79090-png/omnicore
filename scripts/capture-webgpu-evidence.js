#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  createWebGPUComputeDispatchPlan,
  createWebGPUHardwareEvidencePayload,
  createWebGPUInstancingDescriptor,
  createWebGPUTextureArrayBatch
} from '../src/renderer/WebGPURenderer.js';

export function captureWebGPUEvidence({
  out = path.join('dist', 'webgpu-hardware-evidence.json'),
  device = process.env.OMNICORE_WEBGPU_DEVICE || null,
  browser = process.env.OMNICORE_WEBGPU_BROWSER || null,
  vendor = process.env.OMNICORE_WEBGPU_VENDOR || null,
  architecture = process.env.OMNICORE_WEBGPU_ARCH || null,
  fps = process.env.OMNICORE_WEBGPU_FPS || 0,
  sprites = process.env.OMNICORE_WEBGPU_SPRITES || 1000,
  includeHotPaths = process.env.OMNICORE_WEBGPU_HOT_PATHS === 'true',
  pass = process.env.OMNICORE_WEBGPU_PASS !== 'false'
} = {}) {
  const evidence = createWebGPUHardwareEvidencePayload({
    device,
    browser,
    gpu: { vendor, architecture },
    checks: [
      {
        name: `${sprites} sprites WebGPU smoke`,
        fps: Number(fps),
        sprites: Number(sprites),
        pass
      }
    ],
    notes: ['Generated by scripts/capture-webgpu-evidence.js']
  });
  if (includeHotPaths) evidence.hotPaths = createWebGPUHotPathEvidence({ sprites });
  const target = path.resolve(out);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, `${JSON.stringify(evidence, null, 2)}\n`, 'utf8');
  return { ok: true, out: target, evidence };
}

function createWebGPUHotPathEvidence({ sprites = 1000 } = {}) {
  const spriteCount = Math.max(1, Number(sprites) || 1000);
  const instances = Array.from({ length: Math.min(spriteCount, 64) }, (_, index) => ({
    x: (index % 16) * 16,
    y: Math.floor(index / 16) * 16,
    width: 16,
    height: 16
  }));
  const commands = instances.map((instance, index) => ({
    id: `sprite-${index}`,
    texture: index % 2 === 0 ? 'hero.png' : 'props.png',
    ...instance
  }));
  return {
    instancing: createWebGPUInstancingDescriptor({ instances }),
    textureArray: createWebGPUTextureArrayBatch(commands),
    compute: createWebGPUComputeDispatchPlan({
      task: 'particles',
      items: spriteCount,
      workgroupSize: 64
    })
  };
}

function parseArgs(argv = []) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg.startsWith('--')) continue;
    const key = arg.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith('--')) options[key] = true;
    else {
      options[key] = next;
      index += 1;
    }
  }
  return options;
}

function isCli() {
  return process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
}

if (isCli()) {
  const result = captureWebGPUEvidence(parseArgs(process.argv.slice(2)));
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

export default captureWebGPUEvidence;
